#!/usr/bin/env python3
"""Rejection-phenomena import: workbook -> db/seed/phenomena_seed.json + db/04_seed_phenomena.sql.

Reconstructed: the README describes tools/import_excel.py, but it was not in the supplied package. Rules (docs/import_report.md):
  * Sheet1, row 1 = stage headers (GDC SHOP | CNC SHOP | Pre-treatment Inspection | FINAL Inspection), rows below = names.
  * Original text is kept exactly; a separate normalized key = trim, collapse whitespace runs to one space, upper case
    (identical to Quality.Core.Common.TextNormalizer.NormalizeName for this ASCII data).
  * Within one stage the FIRST occurrence of a normalized name is imported; later duplicates are reported and skipped.
  * Codes: <StageCode>-NNN in workbook order, counting imported rows only.

Usage:  python3 -I tools/import_excel.py [--check]
  --check  regenerate in memory and compare with the committed files (exit 1 on any difference).
"""
import json, re, sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
XLSX = ROOT / "db/seed/Rejection_Phinomina.xlsx"
JSON_OUT = ROOT / "db/seed/phenomena_seed.json"
SQL_OUT = ROOT / "db/04_seed_phenomena.sql"

# Column -> (header expected in row 1, stage code, stage display name). Order = workbook column order.
STAGES = [
    ("A", "GDC SHOP", "GDC_SHOP", "GDC Shop"),
    ("B", "CNC SHOP", "CNC_SHOP", "CNC Shop"),
    ("C", "Pre-treatment Inspection", "PRE_TREATMENT", "Pre-treatment Inspection"),
    ("D", "FINAL Inspection", "FINAL", "FINAL Inspection"),
]


def normalize(value: str) -> str:
    return re.sub(r"\s+", " ", value.strip()).upper()


def read_workbook():
    ws = openpyxl.load_workbook(XLSX, read_only=True, data_only=True)["Sheet1"]
    grid = [list(r) for r in ws.iter_rows(values_only=True)]
    rows, stages = [], {}
    for col_index, (col, header, code, name) in enumerate(STAGES):
        actual = grid[0][col_index]
        if actual != header:
            sys.exit(f"Unexpected header in {col}1: {actual!r} (expected {header!r})")
        seen, n_imported, raw, skipped = {}, 0, 0, 0
        for r in range(1, len(grid)):
            v = grid[r][col_index] if col_index < len(grid[r]) else None
            if v is None or (isinstance(v, str) and v.strip() == ""):
                continue
            if not isinstance(v, str):
                sys.exit(f"Non-text value in {col}{r + 1}: {v!r}")
            raw += 1
            cell = f"{col}{r + 1}"
            norm = normalize(v)
            if norm in seen:
                skipped += 1
                rows.append(dict(stageCode=code, cell=cell, original=v, normalized=norm, code=None, status="SKIPPED_DUPLICATE", duplicateOf=seen[norm]))
                continue
            n_imported += 1
            seen[norm] = cell
            rows.append(dict(stageCode=code, cell=cell, original=v, normalized=norm, code=f"{code}-{n_imported:03d}", status="IMPORTED", duplicateOf=None))
        stages[code] = dict(header=header, name=name, raw=raw, imported=n_imported, skipped=skipped)
    return stages, rows


def sql_str(s: str) -> str:
    return "N'" + s.replace("'", "''") + "'"


def render_sql(stages, rows) -> str:
    out = [
        "-- 04_seed_phenomena.sql  (GENERATED by tools/import_excel.py - do not edit by hand)",
        f"-- Source: {XLSX.name}.  Run in QualityMasterDB after 01 and 03.",
        "-- Idempotent: a (stage, normalized name) that already exists is never inserted again, renamed or deleted.",
        "-- Codes: a new name gets its workbook code (<stage>-NNN) when that code is free. If the code is already used (the",
        "-- workbook gained a row in the middle, or an administrator renamed a seeded phenomenon), the name gets the next free",
        "-- number of its stage instead, under the same per-stage lock the API uses, so a re-run never fails on a duplicate code.",
        "-- The check at the end verifies that every seeded NAME is present. Read docs/DATABASE_RUNBOOK.md before re-running.",
        "SET NOCOUNT ON; SET XACT_ABORT ON;",
        "BEGIN TRANSACTION;",
        "DECLARE @inserted int = 0, @lock int;",
        "DECLARE @seed TABLE (StageCode nvarchar(30) NOT NULL, Code nvarchar(30) NOT NULL, Name nvarchar(200) NOT NULL, Norm nvarchar(200) NOT NULL);",
        "",
    ]
    for _, _, code, name in STAGES:
        st = stages[code]
        imported = [r for r in rows if r["stageCode"] == code and r["status"] == "IMPORTED"]
        out.append(f"-- {name}: {st['raw']} Excel rows, {st['imported']} imported, {st['skipped']} skipped (duplicate)")
        out.append(f"SELECT @lock = Id FROM qa.InspectionStages WITH (UPDLOCK, HOLDLOCK) WHERE StageCode = N'{code}';   -- same lock as the API's code allocation")
        out.append("INSERT INTO @seed (StageCode, Code, Name, Norm) VALUES")
        vals = [f"  (N'{code}', {sql_str(r['code'])}, {sql_str(r['original'])}, {sql_str(r['normalized'])})" for r in imported]
        out.append(",\n".join(vals) + ";")
        out.append(f"""WITH missing AS (
    SELECT sd.Code, sd.Name, sd.Norm, s.Id AS StageId,
           CASE WHEN EXISTS (SELECT 1 FROM qa.RejectionPhenomena p WHERE p.PhenomenonCode = sd.Code) THEN 1 ELSE 0 END AS Clash
    FROM @seed sd JOIN qa.InspectionStages s ON s.StageCode = sd.StageCode
    WHERE sd.StageCode = N'{code}'
      AND NOT EXISTS (SELECT 1 FROM qa.RejectionPhenomena p WHERE p.InspectionStageId = s.Id AND p.NormalizedName = sd.Norm)),
hi AS (
    SELECT ISNULL(MAX(z.n), 0) AS n FROM (
        SELECT TRY_CAST(RIGHT(p.PhenomenonCode, 3) AS int) AS n FROM qa.RejectionPhenomena p WHERE p.PhenomenonCode LIKE N'{code}-[0-9][0-9][0-9]'
        UNION ALL SELECT TRY_CAST(RIGHT(m.Code, 3) AS int) FROM missing m WHERE m.Clash = 0) z)
INSERT INTO qa.RejectionPhenomena (PhenomenonCode, PhenomenonName, NormalizedName, InspectionStageId, IsActive)
SELECT CASE WHEN m.Clash = 0 THEN m.Code
            ELSE N'{code}-' + RIGHT(N'000' + CAST(hi.n + ROW_NUMBER() OVER (PARTITION BY m.Clash ORDER BY m.Code) AS nvarchar(10)), 3) END,
       m.Name, m.Norm, m.StageId, 1
FROM missing m CROSS JOIN hi;""")
        out.append("SET @inserted += @@ROWCOUNT;")
        out.append("")
    summary = json.dumps({c: {k: stages[c][k] for k in ("raw", "imported", "skipped")} for _, _, c, _ in STAGES})
    out.append("-- Audit record of the import (only when this run inserted something; a no-op re-run leaves no audit row)")
    out.append("IF @inserted > 0")
    out.append("    INSERT INTO qa.AuditLog (UserId, Action, EntityType, EntityId, OldValue, NewValue)")
    out.append(f"    VALUES (NULL, N'EXCEL_IMPORT', N'RejectionPhenomena', NULL, NULL, {sql_str(summary)});")
    out.append("")
    out.append("-- Post-condition check: abort and roll back unless every seeded (stage, name) is present")
    out.append("IF EXISTS (SELECT 1 FROM @seed sd JOIN qa.InspectionStages s ON s.StageCode = sd.StageCode")
    out.append("           WHERE NOT EXISTS (SELECT 1 FROM qa.RejectionPhenomena p WHERE p.InspectionStageId = s.Id AND p.NormalizedName = sd.Norm))")
    out.append("    THROW 50001, N'Seed check failed: some seeded phenomena are missing after the import.', 1;")
    for _, _, code, _ in STAGES:
        n = stages[code]["imported"]
        out.append(f"IF (SELECT COUNT(*) FROM @seed WHERE StageCode = N'{code}') <> {n} THROW 50001, N'Seed check failed for {code}: the script should hold {n} seeded names', 1;")
    out.append("COMMIT TRANSACTION;")
    out.append("PRINT N'Phenomena seed complete.';")
    return "\n".join(out) + "\n"


def render_json(stages, rows) -> str:
    return json.dumps(dict(source=XLSX.name, stages=stages, rows=rows), indent=2, ensure_ascii=False) + "\n"


def main():
    stages, rows = read_workbook()
    sql, js = render_sql(stages, rows), render_json(stages, rows)
    if "--check" in sys.argv:
        ok = True
        committed = json.loads(JSON_OUT.read_text(encoding="utf-8"))
        if committed != json.loads(js):
            ok = False; print("DIFF: phenomena_seed.json content differs from the workbook")
        if SQL_OUT.read_text(encoding="utf-8") != sql:
            ok = False; print("DIFF: 04_seed_phenomena.sql differs from what the workbook generates")
        print("check:", "OK" if ok else "FAILED")
        sys.exit(0 if ok else 1)
    JSON_OUT.write_text(js, encoding="utf-8"); SQL_OUT.write_text(sql, encoding="utf-8")
    tot = {k: sum(s[k] for s in stages.values()) for k in ("raw", "imported", "skipped")}
    print(f"raw {tot['raw']}, imported {tot['imported']}, skipped {tot['skipped']} -> {JSON_OUT.name}, {SQL_OUT.name}")


if __name__ == "__main__":
    main()
